class FakeCloud:
    """Records every request; ``steps`` is the list of statuses the poll returns in turn."""

    def __init__(self, *, config=CLOUD_YAML, steps=("running", "succeeded"), submit=None, config_resp=None):
        self.config, self.steps, self.requests = config, list(steps), []
        self.submit, self.config_resp = submit, config_resp

    def deletes(self):
        return [r for r in self.requests if r.method == "DELETE"]

    def __call__(self, request: httpx.Request) -> httpx.Response:
        self.requests.append(request)
        path = request.url.path
        if request.method == "POST" and path == mp.BUILDS_PATH:
            return self.submit(request) if self.submit else httpx.Response(202, json={"build_id": "b1"})
        if path == f"{mp.BUILDS_PATH}/b1":
            step = self.steps.pop(0) if len(self.steps) > 1 else self.steps[0]
            return httpx.Response(200, json={"status": step, "error": "boom" if step == "failed" else None})
        if request.method == "DELETE" and path == f"{mp.BUILDS_PATH}/b1":
            return httpx.Response(202, json={"status": "deleting"})
        if path == f"{mp.BUILDS_PATH}/b1/config":
            return self.config_resp(request) if self.config_resp else httpx.Response(200, text=self.config)
        return httpx.Response(404, json={"detail": "no such route"})


@pytest.fixture
def env(tmp_path, monkeypatch):
    monkeypatch.setenv(mp.KEY_ENV, KEY)
    monkeypatch.setenv(mp.file_loader.CONFIG_PATH_ENV, str(tmp_path / "config" / "memory.yml"))
    (tmp_path / "config").mkdir()
    (tmp_path / "config" / "memory.yml").write_text("memory_categories:\n  facts:\n    enabled: true\n")
    monkeypatch.setattr(mp, "POLL_SECONDS", 0.0)
    mp.reset_for_tests()
    mp.file_loader.pin_scoping_mode(None)
    yield tmp_path / "config"
    mp.reset_for_tests()
    mp.file_loader.pin_scoping_mode(None)


def _app(cloud, monkeypatch) -> FastAPI:
    monkeypatch.setattr(mp, "_transport", httpx.MockTransport(cloud))
    app = FastAPI()
    app.include_router(mp.router)
    app.dependency_overrides[get_sdk_auth] = lambda: object()
    return app


def _wait(client, job_id, until=("succeeded", "invalid", "failed"), seconds=5):
    end = time.time() + seconds
    while time.time() < end:
        body = client.get(f"/v1/maca/jobs/{job_id}").json()
        if body["status"] in until:
            return body
        time.sleep(0.02)
    raise AssertionError(f"job did not finish: {body}")


def _start(client, text=USECASE, relationship="b2b"):
    body = {"usecase_markdown": text}
    if relationship is not None:
        body["user_relationship"] = relationship
    return client.post("/v1/maca/generate", json=body)


