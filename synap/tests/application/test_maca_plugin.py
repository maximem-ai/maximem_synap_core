def test_a_job_survives_a_restart_and_a_running_one_is_picked_up_again(env, monkeypatch):
    cloud = FakeCloud(steps=("running",))
    with TestClient(_app(cloud, monkeypatch)) as c:
        job_id = _start(c).json()["job_id"]
