# --------------------------------------------------------------------------- the key never leaks

def test_the_key_never_appears_in_a_response_a_job_file_or_a_log(env, monkeypatch, caplog):
    # Cloud echoes the key back in its error body, the worst case.
    echo = lambda r: httpx.Response(401, json={"detail": f"bad key {KEY} / Authorization: Bearer {KEY}"})
    caplog.set_level(logging.DEBUG)
    with TestClient(_app(FakeCloud(submit=echo), monkeypatch)) as c:
        start = _start(c)
        body = _wait(c, start.json()["job_id"])
        listed = c.get(f"/v1/maca/jobs/{body['job_id']}").text
    everything = [start.text, json.dumps(body), listed, caplog.text]
    everything += [p.read_text() for p in (env / ".maca" / "jobs").glob("*.json")]
    everything += [p.read_text() for p in env.glob("memory*.yml")]
    assert all(KEY not in text for text in everything)
    assert "[key removed]" in body["message"]


