def test_a_job_saves_the_generated_config_and_leaves_memory_yml_alone(env, monkeypatch):
    cloud = FakeCloud()
    before = (env / "memory.yml").read_text()
    with TestClient(_app(cloud, monkeypatch)) as c:
        r = _start(c)
        assert r.status_code == 200
        body = _wait(c, r.json()["job_id"])
    assert body["status"] == "succeeded"
    assert body["config_file"] == mp.GENERATED_NAME
    assert (env / "memory.yml").read_text() == before
    saved = (env / mp.GENERATED_NAME).read_text()
    assert saved.startswith("# Generated by the MACA plugin")
    assert "consolidation" in saved.splitlines()[2]  # the header says what was left out
    cfg = yaml.safe_load(saved)
    assert "consolidation" not in cfg and "anticipation" not in cfg["retrieval_config"]
    assert body["yaml"] == saved
    assert "consolidation" in body["removed_fields"]
    mp.file_loader.parse_and_validate(saved, "memory.generated.yml")


